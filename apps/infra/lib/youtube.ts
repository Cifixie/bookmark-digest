/**
 * YouTube transcript extraction — shared between the standalone
 * `scripts/youtube-transcript.ts` CLI and the `push-source extract` subcommand
 * of `scripts/push-source.ts`.
 *
 * This used to run inside the ingest-url Lambda. It was pulled out because it
 * doesn't work reliably from there: YouTube's InnerTube captions endpoint
 * silently omits caption tracks (200 OK, no error) for a large share of
 * requests from Lambda's shared/datacenter IP ranges, while working fine from
 * a residential IP. That isn't fixable from our side, so the automatic path is
 * gone (see plans/source-quality-and-upload.md) and these run on the user's own
 * machine.
 */

const PLAYER_URL = "https://youtubei.googleapis.com/youtubei/v1/player?prettyPrint=false";

/**
 * InnerTube clients, tried in order. Which clients are served caption tracks
 * changes without notice, and a client that is refused returns a 200 with the
 * captions key simply absent rather than an error — so "no tracks" is not a
 * reliable signal that the video has no captions until every client has been
 * tried.
 */
